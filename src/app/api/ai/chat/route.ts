// Post-processor for customer-facing chat replies (shortReply, detailedReply, followUpHook)
// Removes textbook citations like "(មេរៀនទី ៨)" or stiff AI boilerplate so it reads 100% like a real human expert in Chat
function cleanCustomerReply(input: string): string {
  let out = cleanThaiLeakage(input);
  // Remove parenthetical lesson citations e.g. (មេរៀនទី ៨) or (មេរៀនទី ១, ៣)
  out = out.replace(/\s*\(\s*មេរៀនទី[^)]*\)/g, "");
  // Remove stiff formal company legal suffix in chat replies
  out = out.replace(/របស់ក្រុមហ៊ុន\s*វណ្ណ\s*ស៊ីថា\s*ត្រេឌីង\s*ឯ\.ក/g, "");
  // Remove robotic translated empathy opener if present
  out = out.replace(/អរគុណបងស្រីដែលបានចែករំលែកការព្រួយបារម្ភ[^។!]*[។!]\s*/g, "");
  return out.replace(/[ \t]{2,}/g, " ").trim();
}

function parseOrRecoverStructured(rawText: string): {
  sellerCoaching: string;
  shortReply: string;
  detailedReply: string;
  followUpHook: string;
} | null {
  const cleaned = rawText
    .replace(/^```json\s*/i, "")
    .replace(/^```\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim();

  try {
    const parsed = JSON.parse(cleaned);
    if (
      parsed &&
      (parsed.sellerCoaching || parsed.shortReply || parsed.detailedReply || parsed.followUpHook)
    ) {
      return {
        sellerCoaching: cleanThaiLeakage(String(parsed.sellerCoaching || "")),
        shortReply: cleanCustomerReply(String(parsed.shortReply || "")),
        detailedReply: cleanCustomerReply(String(parsed.detailedReply || "")),
        followUpHook: cleanCustomerReply(String(parsed.followUpHook || "")),
      };
    }
  } catch {
    const extractField = (field: string, nextFields: string[]): string => {
      const nextPattern = nextFields.length
        ? `(?=",\\s*"(?:${nextFields.join("|")})"|"\\s*\\}\\s*$|$)`
        : `(?="\\s*\\}\\s*$|$)`;
      const regex = new RegExp(`"${field}"\\s*:\\s*"([\\s\\S]*?)${nextPattern}`);
      const match = cleaned.match(regex);
      if (!match?.[1]) return "";
      return cleanThaiLeakage(
        match[1]
          .replace(/\\n/g, "\n")
          .replace(/\\"/g, '"')
          .replace(/\\\\/g, "\\")
          .replace(/",\s*$/, "")
          .trim()
      );
    };

    const sellerCoaching = extractField("sellerCoaching", ["shortReply", "detailedReply", "followUpHook"]);
    const shortReply = cleanCustomerReply(extractField("shortReply", ["detailedReply", "followUpHook"]));
    const detailedReply = cleanCustomerReply(extractField("detailedReply", ["followUpHook"]));
    const followUpHook = cleanCustomerReply(extractField("followUpHook", []));

    if (sellerCoaching || shortReply || detailedReply || followUpHook) {
      return { sellerCoaching, shortReply, detailedReply, followUpHook };
    }
  }
  return null;
}

