export async function POST(req: Request) {
  try {
    const { prompt, category } = await req.json();
    if (!prompt || typeof prompt !== "string" || !prompt.trim()) {
      return NextResponse.json(
        { ok: false, message: "សូមបញ្ចូលសំណួរ ឬសារដែលភ្ញៀវសួរ!" },
        { status: 400 }
      );
    }

    const cleanPrompt = cleanThaiLeakage(prompt.trim());
    const apiKey = (process.env.GEMINI_API_KEY || "").trim();

    if (apiKey) {
      const categoryLabel = category ? `[ប្រភេទបញ្ហា៖ ${category}]\n` : "";
      const userPrompt = `${categoryLabel}ភ្ញៀវឆាតមកសួរ ឬនិយាយថា៖\n"${cleanPrompt}"\n\nសូមឆ្លើយតបជាទម្រង់ JSON (sellerCoaching, shortReply, detailedReply, followUpHook) ដោយប្រើសម្តីមនុស្សពិតៗនិយាយគ្នាក្នុង Chat (ហាមដាច់ខាតប្រើសម្តីបកប្រែបែប AI ដូចជា "អរគុណដែលបានចែករំលែកការព្រួយបារម្ភ" ឬ "ការវិនិយោគ" ឬឈ្មោះក្រុមហ៊ុនវែងៗ) តែត្រូវពន្យល់ឱ្យច្បាស់លាស់ ម៉ឺងម៉ាត់ និងស៊ីជម្រៅបែបអ្នកជំនាញរោគស្ត្រីពិតៗតាមសៀវភៅរោគស្ត្រីទាំង ១៧ មេរៀន (អក្សរខ្មែរសុទ្ធ ១០០% ហាមលាយអក្សរថៃ)។`;

      const models = [
        "gemini-3.5-flash-lite",
        "gemini-3.5-flash",
        "gemini-3-flash-preview",
        "gemini-3.8-flash",
      ];

      for (const modelName of models) {
        try {
          const url = `https://generativelanguage.googleapis.com/v1beta/models/${modelName}:generateContent?key=${apiKey}`;
          const response = await fetch(url, {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
            },
            body: JSON.stringify({
              system_instruction: {
                parts: [{ text: SYSTEM_INSTRUCTION }],
              },
              contents: [
                {
                  role: "user",
                  parts: [{ text: userPrompt }],
                },
              ],
              generationConfig: {
                temperature: 0.55,
                topP: 0.9,
                maxOutputTokens: 4096,
                responseMimeType: "application/json",
              },
            }),
          });

          const data = await response.json();
          const parts = data?.candidates?.[0]?.content?.parts;
          const combinedText = Array.isArray(parts)
            ? parts
                .filter((p: any) => !p?.thought && typeof p?.text === "string")
                .map((p: any) => p.text)
                .join("")
            : "";

          if (response.ok && combinedText) {
            const rawText = cleanThaiLeakage(combinedText);
            const structured = parseOrRecoverStructured(rawText);
            if (structured) {
              return NextResponse.json({
                ok: true,
                model: modelName,
                structured,
                text: structured.detailedReply || structured.shortReply,
              });
            }
            return NextResponse.json({
              ok: true,
              model: modelName,
              text: rawText,
            });
          }
        } catch {
          // Try next model
        }
      }
    }

    const fallbackStructured = buildSmartBookFallback(cleanPrompt);
    return NextResponse.json({
      ok: true,
      model: "emmi-book-engine",
      structured: fallbackStructured,
      text: fallbackStructured.detailedReply,
    });
  } catch (error: any) {
    return NextResponse.json(
      { ok: false, message: error.message || "Internal server error" },
      { status: 500 }
    );
  }
}
