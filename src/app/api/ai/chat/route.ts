// Resilient parser so even if JSON is ever truncated or wrapped in markdown, it never shows raw JSON code
function parseOrRecoverStructured(rawText: string): {
  sellerCoaching: string;
  shortReply: string;
  detailedReply: string;
  followUpHook: string;
} | null {
  const cleaned = rawText
    .replace(/^```json\s*/i, "")
    .replace(/^```\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim();

  try {
    const parsed = JSON.parse(cleaned);
    if (
      parsed &&
      (parsed.sellerCoaching || parsed.shortReply || parsed.detailedReply || parsed.followUpHook)
    ) {
      return {
        sellerCoaching: cleanThaiLeakage(String(parsed.sellerCoaching || "")),
        shortReply: cleanThaiLeakage(String(parsed.shortReply || "")),
        detailedReply: cleanThaiLeakage(String(parsed.detailedReply || "")),
        followUpHook: cleanThaiLeakage(String(parsed.followUpHook || "")),
      };
    }
  } catch {
    // Fallback regex extraction if JSON was truncated or had unescaped characters
    const extractField = (field: string, nextFields: string[]): string => {
      const nextPattern = nextFields.length
        ? `(?=",\\s*"(?:${nextFields.join("|")})"|"\\s*\\}\\s*$|$)`
        : `(?="\\s*\\}\\s*$|$)`;
      const regex = new RegExp(`"${field}"\\s*:\\s*"([\\s\\S]*?)${nextPattern}`);
      const match = cleaned.match(regex);
      if (!match?.[1]) return "";
      return cleanThaiLeakage(
        match[1]
          .replace(/\\n/g, "\n")
          .replace(/\\"/g, '"')
          .replace(/\\\\/g, "\\")
          .replace(/",\s*$/, "")
          .trim()
      );
    };

    const sellerCoaching = extractField("sellerCoaching", ["shortReply", "detailedReply", "followUpHook"]);
    const shortReply = extractField("shortReply", ["detailedReply", "followUpHook"]);
    const detailedReply = extractField("detailedReply", ["followUpHook"]);
    const followUpHook = extractField("followUpHook", []);

    if (sellerCoaching || shortReply || detailedReply || followUpHook) {
      return { sellerCoaching, shortReply, detailedReply, followUpHook };
    }
  }
  return null;
}

